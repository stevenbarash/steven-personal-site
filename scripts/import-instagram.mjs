#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const APP_ID = '936619743392459';
const DEFAULT_LIMIT = 36;
const PAGE_SIZE = 12;
const MAX_RETRIES = 2;
const execFileAsync = promisify(execFile);

function getArg(name, fallback = '') {
  const index = process.argv.indexOf(`--${name}`);
  if (index === -1) return fallback;
  return process.argv[index + 1] ?? fallback;
}

function sleep(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

function normalizeText(input) {
  return (input || '')
    .replace(/\r/g, '')
    .replace(/https?:\/\/\S+/gi, ' ')
    .replace(/#[\p{L}\p{N}_]+/gu, ' ')
    .replace(/@[\p{L}\p{N}._]+/gu, ' ')
    .replace(/[\p{Extended_Pictographic}\p{Regional_Indicator}\uFE0F]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function sanitizeTitle(caption, fallback) {
  if (!caption) return fallback;

  const lines = caption
    .split('\n')
    .map((line) => normalizeText(line))
    .filter(Boolean);

  if (!lines.length) return fallback;

  const candidate = (lines.find((line) => line.length >= 4) || lines[0])
    .replace(/^[\s:;|,./\\-]+/, '')
    .trim();
  if (!candidate) return fallback;

  return candidate.slice(0, 90).trim();
}

function formatDate(timestampSeconds) {
  if (!timestampSeconds) return 'Unknown';
  const date = new Date(timestampSeconds * 1000);
  const year = date.getUTCFullYear();
  const month = `${date.getUTCMonth() + 1}`.padStart(2, '0');
  const day = `${date.getUTCDate()}`.padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function escapeString(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function buildDataFile(items) {
  const lines = [];
  lines.push("import type { PhotoItem } from '@/types';");
  lines.push('');
  lines.push('// This file is auto-generated by scripts/import-instagram.mjs');
  lines.push('export const photoLibrary: PhotoItem[] = [');

  for (const item of items) {
    lines.push('  {');
    lines.push(`    id: '${escapeString(item.id)}',`);
    lines.push(`    title: '${escapeString(item.title)}',`);
    lines.push(`    src: '${escapeString(item.src)}',`);
    lines.push(`    alt: '${escapeString(item.alt)}',`);
    lines.push("    album: 'Instagram',");
    lines.push(`    takenAt: '${escapeString(item.takenAt)}',`);
    lines.push(`    location: '${escapeString(item.location)}',`);
    lines.push(`    camera: '${escapeString(item.camera)}',`);
    lines.push(`    width: ${item.width},`);
    lines.push(`    height: ${item.height},`);
    lines.push('  },');
  }

  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

function makeHeaders(username) {
  return [
    `x-ig-app-id: ${APP_ID}`,
    'x-asbd-id: 129477',
    'x-requested-with: XMLHttpRequest',
    `referer: https://www.instagram.com/${username}/`,
    'user-agent: Mozilla/5.0',
    'accept: */*',
  ];
}

async function runCurlJson(url, headers) {
  const args = ['-sS', url];
  for (const header of headers) {
    args.push('-H', header);
  }
  const { stdout } = await execFileAsync('curl', args, { maxBuffer: 1024 * 1024 * 20 });
  return JSON.parse(stdout);
}

async function fetchJsonWithRetry(url, headers, context) {
  let lastError = null;

  for (let attempt = 1; attempt <= MAX_RETRIES; attempt += 1) {
    try {
      const payload = await runCurlJson(url, headers);
      if (payload?.status === 'fail') {
        const message = payload?.message || 'Unknown failure';
        const shouldRetry = /wait a few minutes|try again|login/i.test(message);
        if (!shouldRetry || attempt === MAX_RETRIES) {
          throw new Error(`${context} failed: ${message}`);
        }
        lastError = `${context} attempt ${attempt} failed (${message}), retrying...`;
      } else {
        return payload;
      }
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown curl error';
      const shouldRetry = /wait a few minutes|try again|timed out|temporarily|login/i.test(message);
      if (!shouldRetry || attempt === MAX_RETRIES) {
        throw new Error(`${context} failed: ${message}`);
      }
      lastError = `${context} attempt ${attempt} failed (${message}), retrying...`;
    }

    const backoffMs = Math.min(120000, 5000 * (2 ** (attempt - 1)));
    console.warn(lastError);
    await sleep(backoffMs);
  }

  throw new Error(lastError || `${context} failed`);
}

async function fetchProfile(username, headers) {
  const endpoint = `https://i.instagram.com/api/v1/users/web_profile_info/?username=${encodeURIComponent(username)}`;
  return fetchJsonWithRetry(endpoint, headers, 'Profile request');
}

async function fetchFeedPage(userId, headers, maxId = '') {
  const params = new URLSearchParams({ count: `${PAGE_SIZE}` });
  if (maxId) params.set('max_id', maxId);
  const endpoint = `https://i.instagram.com/api/v1/feed/user/${userId}/?${params.toString()}`;
  return fetchJsonWithRetry(endpoint, headers, 'Timeline request');
}

function pickImageUrl(item) {
  if (item?.image_versions2?.candidates?.[0]?.url) {
    return item.image_versions2.candidates[0].url;
  }

  if (item?.carousel_media?.[0]?.image_versions2?.candidates?.[0]?.url) {
    return item.carousel_media[0].image_versions2.candidates[0].url;
  }

  return '';
}

function pickDimensions(item) {
  const width = item?.original_width
    || item?.image_versions2?.candidates?.[0]?.width
    || item?.carousel_media?.[0]?.original_width
    || 1080;
  const height = item?.original_height
    || item?.image_versions2?.candidates?.[0]?.height
    || item?.carousel_media?.[0]?.original_height
    || 1080;
  return { width, height };
}

async function downloadImage(url, destinationPath) {
  await execFileAsync('curl', [
    '-sS',
    '-L',
    '-o',
    destinationPath,
    '-H',
    'user-agent: Mozilla/5.0',
    '-H',
    'accept: image/*',
    url,
  ]);
}

async function collectItems(username, limit, headers) {
  const profile = await fetchProfile(username, headers);
  const userId = profile?.data?.user?.id;
  const profileEdges = profile?.data?.user?.edge_owner_to_timeline_media?.edges ?? [];

  if (!userId) {
    throw new Error(`Unable to resolve user id for @${username}`);
  }

  const collected = [];
  const seenIds = new Set();
  let maxId = '';
  let hasMore = true;

  try {
    while (hasMore && collected.length < limit) {
      const page = await fetchFeedPage(userId, headers, maxId);
      const items = page?.items ?? [];

      for (const item of items) {
        const itemId = `${item?.code || item?.pk || ''}`;
        if (!itemId || seenIds.has(itemId)) continue;
        seenIds.add(itemId);
        collected.push(item);
        if (collected.length >= limit) break;
      }

      hasMore = Boolean(page?.more_available);
      maxId = page?.next_max_id || '';
      if (!maxId) break;
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Unknown timeline error';
    console.warn(`Timeline pagination unavailable (${message}). Falling back to profile feed.`);
    return profileEdges
      .map((edge) => edge?.node)
      .filter(Boolean)
      .map((node) => ({
        code: node.shortcode,
        pk: node.id,
        caption: { text: node.edge_media_to_caption?.edges?.[0]?.node?.text ?? '' },
        location: { name: node.location?.name ?? 'Unknown' },
        taken_at: node.taken_at_timestamp,
        original_width: node.dimensions?.width,
        original_height: node.dimensions?.height,
        image_versions2: {
          candidates: [
            {
              url: node.display_url,
              width: node.dimensions?.width,
              height: node.dimensions?.height,
            },
          ],
        },
      }))
      .slice(0, limit);
  }

  return collected;
}

async function main() {
  const username = getArg('username');
  const limit = Number.parseInt(getArg('limit', `${DEFAULT_LIMIT}`), 10);

  if (!username) {
    throw new Error('Usage: node scripts/import-instagram.mjs --username <instagram_handle> [--limit 36]');
  }

  if (Number.isNaN(limit) || limit < 1) {
    throw new Error('The --limit value must be a positive number.');
  }

  const rootDir = process.cwd();
  const outputDir = path.join(rootDir, 'public', 'images', 'photos', 'instagram');
  const dataFilePath = path.join(rootDir, 'src', 'data', 'photos.ts');
  const headers = makeHeaders(username);

  await fs.mkdir(outputDir, { recursive: true });

  const timelineItems = await collectItems(username, limit, headers);

  if (!timelineItems.length) {
    throw new Error(`No timeline media found for @${username}.`);
  }

  const selected = timelineItems
    .map((item) => ({ item, imageUrl: pickImageUrl(item) }))
    .filter((entry) => entry.imageUrl)
    .slice(0, limit);

  const photoItems = [];

  for (let i = 0; i < selected.length; i += 1) {
    const { item, imageUrl } = selected[i];
    const shortcode = item.code || item.pk || `${i + 1}`;
    const filename = `${shortcode}.jpg`;
    const relativeSrc = `/images/photos/instagram/${filename}`;
    const destinationPath = path.join(outputDir, filename);

    await downloadImage(imageUrl, destinationPath);

    const caption = item?.caption?.text ?? '';
    const title = sanitizeTitle(caption, `Instagram Photo ${i + 1}`);
    const location = normalizeText(item?.location?.name || 'Unknown') || 'Unknown';
    const dimensions = pickDimensions(item);

    photoItems.push({
      id: `ig-${shortcode}`,
      title,
      src: relativeSrc,
      alt: `${title} by ${username}`,
      takenAt: formatDate(item?.taken_at),
      location,
      camera: 'Instagram Upload',
      width: dimensions.width,
      height: dimensions.height,
    });
  }

  const fileContents = buildDataFile(photoItems);
  await fs.writeFile(dataFilePath, fileContents, 'utf8');

  console.log(`Imported ${photoItems.length} photos from @${username}`);
  console.log(`Saved images to ${path.relative(rootDir, outputDir)}`);
  console.log(`Updated ${path.relative(rootDir, dataFilePath)}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
